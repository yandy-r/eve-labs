"""Answers files: question id -> value, as TOML or JSON.

TOML (``--save-answers`` writes this form)::

    schema = 1
    host = "eve2"

    [answers]
    "image/qemu/nxosv9k/nxosv9k-9300v-10.3.3.F" = "nxosv9k-9300v-10.5.1.F"
    "qemu_version/4.1.0" = "8.2.0"
    "ram/16384" = "keep"

JSON: ``{"<id>": "<value>"}``, or a ``scan --json`` document whose questions
carry an ``"answer"`` field.
"""

from __future__ import annotations

import json
import tomllib
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from evelab.common import tomlw
from evelab.common.errors import EveLabError

__all__ = ["ANSWERS_SCHEMA", "load_answers", "save_answers"]

ANSWERS_SCHEMA = 1


def _bad(path: Path, msg: str) -> EveLabError:
    return EveLabError(f"{path}: {msg}", code="BAD_ANSWER")


def _strings(data: Mapping[str, Any], path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    for key, value in data.items():
        if isinstance(value, bool) or not isinstance(value, str | int):
            raise _bad(path, f"answer for {key!r} must be a string or number")
        out[str(key)] = str(value)
    return out


def _from_scan(data: Mapping[str, Any], path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    for lab in data.get("labs", []):
        for q in lab.get("questions", []):
            if q.get("answer") is not None:
                out.update(_strings({q["id"]: q["answer"]}, path))
    return out


def load_answers(path: Path) -> dict[str, str]:
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise _bad(path, str(exc)) from exc
    if path.suffix.lower() == ".json":
        try:
            data = json.loads(text)
        except ValueError as exc:
            raise _bad(path, f"invalid JSON: {exc}") from exc
        if not isinstance(data, dict):
            raise _bad(path, "expected a JSON object")
        if "labs" in data:
            return _from_scan(data, path)
        return _strings(data, path)
    try:
        doc = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        raise _bad(path, f"invalid TOML: {exc}") from exc
    if doc.get("schema", ANSWERS_SCHEMA) != ANSWERS_SCHEMA:
        raise _bad(path, f"unsupported schema {doc.get('schema')!r}")
    table = doc.get("answers", {})
    if not isinstance(table, dict):
        raise _bad(path, "[answers] must be a table")
    return _strings(table, path)


def save_answers(path: Path, answers: Mapping[str, str], host: str = "") -> None:
    doc: dict[str, Any] = {"schema": ANSWERS_SCHEMA}
    if host:
        doc["host"] = host
    doc["answers"] = dict(sorted(answers.items()))
    path.parent.mkdir(parents=True, exist_ok=True)
    tomlw.dump(path, doc, header="Generated by eve-analyze (answers, schema 1).")
